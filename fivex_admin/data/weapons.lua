function FindWeaponInCatalog(name)
    if not name then return nil end
    name = string.upper(tostring(name))
    for i = 1, #WeaponCatalog do
        if WeaponCatalog[i].name == name then
            return WeaponCatalog[i]
        end
    end
    return nil
end
