function FindVehicleInCatalog(model)
    if not model then return nil end
    model = string.lower(tostring(model))
    for i = 1, #VehicleCatalog do
        if VehicleCatalog[i].model == model then
            return VehicleCatalog[i]
        end
    end
    return nil
end
